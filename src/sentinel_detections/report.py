"""Build the false-positive report (docs/results.md) from rule evaluations."""

from __future__ import annotations

from collections.abc import Iterable
from dataclasses import dataclass
from pathlib import Path, PurePosixPath

from azure.kusto.data import KustoClient

from sentinel_detections.harness import evaluate
from sentinel_detections.manifest import Dataset
from sentinel_detections.rules import RulePair

HEADER = """\
# Detection results

Generated by `scripts/report.py` from the rules, their test cases and the datasets
loaded into the Kusto emulator. Do not edit by hand.

Each rule is run once per dataset. Every dataset falls into one of three groups:

- **Attack hits**: rows the tuned rule returns on its own attack dataset.
- **Cross-hits**: rows the tuned rule returns on other datasets whose manifest
  techniques overlap the rule's `relevantTechniques`. These datasets contain the same
  technique, so hits there are expected and not counted as false positives.
- **False positives (FP)**: rows returned on all other datasets. *FP baseline* uses the
  untuned baseline query from the rule's test case; *FP tuned* uses the rule's query.
"""

COLUMNS = ("Rule", "Technique", "Attack dataset", "Attack hits", "Cross-hits")
NUMERIC_COLUMNS = ("Attack hits", "Cross-hits", "FP baseline", "FP tuned")


@dataclass(frozen=True)
class ResultRow:
    """One rule's line in the results table."""

    name: str
    rule_path: PurePosixPath
    techniques: tuple[str, ...]
    attack_dataset: str
    attack_hits: int
    cross_hits: int
    fp_baseline: int
    fp_tuned: int


def build_rows(
    client: KustoClient,
    database: str,
    pairs: Iterable[RulePair],
    datasets: list[Dataset],
    repo_root: Path,
) -> list[ResultRow]:
    """Evaluate the tuned and baseline query of every rule on every dataset."""
    rows = []
    for pair in sorted(pairs, key=lambda pair: pair.rule.path):
        rule, case = pair.rule, pair.case
        tuned = evaluate(client, database, rule.query, rule, case.attack_dataset, datasets)
        baseline = evaluate(
            client, database, case.baseline_query, rule, case.attack_dataset, datasets
        )
        rows.append(
            ResultRow(
                name=rule.data["name"],
                rule_path=PurePosixPath(rule.path.relative_to(repo_root).as_posix()),
                techniques=rule.relevant_techniques,
                attack_dataset=case.attack_dataset,
                attack_hits=tuned.attack.hits,
                cross_hits=tuned.cross_hit_total,
                fp_baseline=baseline.false_positive_total,
                fp_tuned=tuned.false_positive_total,
            )
        )
    return rows


def render_results(rows: Iterable[ResultRow], output_dir: PurePosixPath) -> str:
    """Render the header and results table as Markdown.

    Rule links are relative to ``output_dir``, the repository folder the file is written to.
    """
    columns = (*COLUMNS, "FP baseline", "FP tuned")
    alignment = ["---:" if column in NUMERIC_COLUMNS else "---" for column in columns]
    lines = [HEADER, f"| {' | '.join(columns)} |", f"| {' | '.join(alignment)} |"]
    up = "/".join([".."] * len(output_dir.parts))
    for row in rows:
        link = f"{up}/{row.rule_path}" if up else str(row.rule_path)
        cells = (
            f"[{row.name}]({link})",
            ", ".join(row.techniques),
            f"`{row.attack_dataset}`",
            str(row.attack_hits),
            str(row.cross_hits),
            str(row.fp_baseline),
            str(row.fp_tuned),
        )
        lines.append(f"| {' | '.join(cells)} |")
    return "\n".join(lines) + "\n"
